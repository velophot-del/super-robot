import api from './client';
export const planningApi = {
  exportPersonal: (id:number) => api.get<Blob>(`/my/plans/${id}/export`,{responseType:'blob'}),
  exportOptions: () => api.get('/planning/exports/options'),
  exportWord: (params: {major:string;start_date:string;weeks:number;cohort?:string}) => api.get<Blob>('/planning/exports/word',{params,responseType:'blob'}),
  selfProfile: () => api.get('/planning/self-profile'),
  selfProfileCourseGroups: () => api.get<{id:number;name:string;course_code:string;department?:string}[]>('/planning/self-profile/course-groups'),
  selfProfileCourses: () => api.get<string[]>('/planning/self-profile/courses'),
  saveSelfProfile: (data: unknown) => api.put('/planning/self-profile',data),
  coursePool: (id:number) => api.get(`/planning/plans/${id}/course-pool`),
  syncCoursePool: (id:number) => api.post(`/planning/plans/${id}/sync-course-pool`),
  placeCourse: (id:number,data:unknown) => api.put(`/planning/plans/${id}/placement`,data),
  unplaceCourse: (id:number,task:number,revision:number) => api.delete(`/planning/plans/${id}/placement/${task}`,{params:{revision}}),
  savePlanGroups: (id:number,data:unknown) => api.put(`/planning/plans/${id}/groups`,data),
  syncCurriculumCourses: (id:number) => api.post(`/planning/curricula/${id}/sync-courses`),
  plans: () => api.get('/planning/plans'),
  createPlan: (data: unknown) => api.post('/planning/plans', data),
  state: (id: number) => api.get(`/planning/plans/${id}`),
  profiles: () => api.get('/planning/profiles'),
  saveProfile: (id: number, data: unknown) => api.put(`/planning/profiles/${id}`, data),
  addTask: (id: number, data: unknown) => api.post(`/planning/plans/${id}/tasks`, data),
  editTask: (id: number, taskId: number, data: unknown) => api.put(`/planning/plans/${id}/tasks/${taskId}`, data),
  setTaskLimits: (id:number,task:number,data:{revision:number;teacher_count:number;max_students:number}) => api.put(`/planning/plans/${id}/tasks/${task}/limits`,data),
  setTaskRoom: (id: number, taskId: number, roomId: number | null) => api.put(`/planning/plans/${id}/tasks/${taskId}/room`, { room_id: roomId }),
  generate: (id: number) => api.post(`/planning/plans/${id}/generate`),
  curricula: () => api.get('/planning/curricula'),
  importCurriculum: (data: FormData) => api.post('/planning/curricula/import',data,{headers:{'Content-Type':'multipart/form-data'}}),
  activateCurriculum: (id: number) => api.post(`/planning/curricula/${id}/activate`),
  open: (id: number) => api.post(`/planning/plans/${id}/open`),
  saveWorkloadEstimate: (id:number,task:number,data:unknown) => api.put(`/planning/plans/${id}/tasks/${task}/workload-estimate`,data),
  myWorkload: (id:number) => api.get(`/planning/plans/${id}/my-workload`),
  saveDraft: (id: number, data: unknown) => api.put(`/planning/plans/${id}/draft`, data),
  submit: (id: number, revision: number) => api.post(`/planning/plans/${id}/submit`, { revision }),
  match: (id: number) => api.post(`/planning/plans/${id}/match`),
  saveMatchWeights: (id:number,data:unknown) => api.put(`/planning/plans/${id}/match-weights`,data),
  saveExamWeeks: (id:number,data:unknown) => api.put(`/planning/plans/${id}/exam-weeks`,data),
  assign: (id: number, data: unknown) => api.post(`/planning/plans/${id}/assign`, data),
  reassign: (id:number,task:number,data:unknown) => api.put(`/planning/plans/${id}/tasks/${task}/assignment`,data),
  publish: (id: number) => api.post(`/planning/plans/${id}/publish`),
  export: (id: number) => api.get(`/planning/plans/${id}/export`,{responseType:'blob'}),
};
